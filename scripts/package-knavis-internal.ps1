function Export-Image {
    param(
        [string]$Image,
        [string]$OutputDirectory,
        [System.Collections.Generic.List[string]]$Manifest
    )

    $inspect = @(docker image inspect $Image --format "{{.Id}}|{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}")
    if ($LASTEXITCODE -ne 0 -or $inspect.Count -eq 0) {
        throw "Required image is not available locally: $Image"
    }
    $safeName = $Image -replace "[:/]", "_"
    $tarPath = Join-Path $OutputDirectory "$safeName.tar"
    Write-Host "==> Exporting $Image" -ForegroundColor Cyan
    Invoke-Checked "docker" @("save", "-o", $tarPath, $Image)
    $Manifest.Add("$Image`t$($inspect[0])")
}

