function Assert-Command {
    param([string]$Name)
    if (-not (Get-Command $Name -ErrorAction SilentlyContinue)) {
        throw "Missing required command: $Name"
    }
}

function Invoke-Checked {
    param(
        [string]$FilePath,
        [string[]]$Arguments
    )

    & $FilePath @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "$FilePath failed with exit code $LASTEXITCODE"
    }
}

function Write-Utf8NoBom {
    param(
        [string]$Path,
        [string]$Content
    )

    [System.IO.File]::WriteAllText(
        $Path,
        $Content,
        (New-Object -TypeName System.Text.UTF8Encoding -ArgumentList $false)
    )
}

function New-RandomSecret {
    param([int]$ByteCount = 32)

    $bytes = New-Object byte[] $ByteCount
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    } finally {
        $generator.Dispose()
    }
    return ([Convert]::ToBase64String($bytes) -replace "\+", "-" -replace "/", "_" -replace "=", "")
}

function Build-Frontend {
    $previous = [Environment]::GetEnvironmentVariable("VITE_BRAND_PROFILE", "Process")
    $previousVersion = [Environment]::GetEnvironmentVariable("VITE_FRONTEND_VERSION", "Process")
    $env:VITE_BRAND_PROFILE = "internal"
    $env:VITE_FRONTEND_VERSION = $Version
    Push-Location (Join-Path $repoRoot "frontend")
    try {
        Write-Host "==> Building internal Knavis frontend" -ForegroundColor Cyan
        & npm ci --silent
        if ($LASTEXITCODE -ne 0) { throw "npm ci failed" }
        & npm run build
        if ($LASTEXITCODE -ne 0) { throw "npm run build failed" }
    } finally {
        Pop-Location
        if ($null -eq $previous) {
            Remove-Item Env:VITE_BRAND_PROFILE -ErrorAction SilentlyContinue
        } else {
            $env:VITE_BRAND_PROFILE = $previous
        }
        if ($null -eq $previousVersion) {
            Remove-Item Env:VITE_FRONTEND_VERSION -ErrorAction SilentlyContinue
        } else {
            $env:VITE_FRONTEND_VERSION = $previousVersion
        }
    }
}

